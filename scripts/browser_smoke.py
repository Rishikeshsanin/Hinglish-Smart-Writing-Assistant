"""Playwright smoke test of the actual Streamlit app and real pretrained model."""

import json
import re
from pathlib import Path

from playwright.sync_api import expect, sync_playwright

BASE_URL = "http://127.0.0.1:8501"
OUTPUT = Path(__file__).resolve().parents[1] / "screenshots"
EXAMPLE = "kal mujhe college jana hai!"
EXPECTED = "कल मुझे कॉलेज जाना है!"


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    checks = []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch(headless=True, args=["--no-sandbox"])
        try:
            for label, viewport in (
                ("desktop", {"width": 1440, "height": 900}),
                ("mobile", {"width": 390, "height": 844}),
            ):
                context = browser.new_context(viewport=viewport, device_scale_factor=1)
                page = context.new_page()
                runtime_errors = []
                page.on("pageerror", lambda error: runtime_errors.append(str(error)))
                page.goto(BASE_URL, wait_until="domcontentloaded", timeout=30000)
                box = page.locator("textarea").first
                expect(box).to_be_visible(timeout=90000)
                box.fill(EXAMPLE)
                box.press("Tab")
                page.get_by_role("button", name=re.compile("Convert to Hindi")).click()
                expect(page.get_by_text("Generated by IndicXlit")).to_be_visible(timeout=180000)
                expect(page.get_by_text(EXPECTED, exact=False)).to_be_visible(timeout=30000)
                assert not runtime_errors, f"{label} JS errors: {runtime_errors}"
                if label == "mobile":
                    # Streamlit has an internally scrolling page. Capture both the
                    # input view and a second image with the real result in view.
                    page.screenshot(path=str(OUTPUT / "mobile-top.png"), full_page=True)
                    page.get_by_text(EXPECTED, exact=False).scroll_into_view_if_needed()
                page.screenshot(path=str(OUTPUT / f"{label}.png"), full_page=True)
                checks.append({
                    "viewport": label,
                    "width": viewport["width"],
                    "input": EXAMPLE,
                    "observed": EXPECTED,
                    "screenshot": f"screenshots/{label}.png",
                    "horizontal_overflow": page.evaluate(
                        "document.documentElement.scrollWidth > window.innerWidth + 4"
                    ),
                })
                page.get_by_role("button", name="Clear", exact=True).click()
                expect(box).to_have_value("", timeout=30000)
                context.close()
        finally:
            browser.close()
    (OUTPUT / "browser-qa.json").write_text(
        json.dumps(checks, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("REAL_STREAMLIT_INDICXLIT_BROWSER_TEST_PASSED", flush=True)
    print(json.dumps(checks, ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
