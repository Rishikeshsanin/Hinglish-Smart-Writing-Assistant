"""Independent public Streamlit Playwright check: actual IndicXlit UI inference.

The test visits only the public IndicWrite app. It does not mock predictions,
read secrets, mutate the deployment, or interact with other user projects.
"""
from __future__ import annotations

import os
from pathlib import Path
import re
import time

from playwright.sync_api import TimeoutError as PlaywrightTimeout
from playwright.sync_api import sync_playwright

URL = "https://hinglish-smart-writing-assistant-indicwrite-rishi.streamlit.app/"
SCREENSHOT = Path(os.environ.get("INDICWRITE_PUBLIC_QA_SCREENSHOT", "public-indicwrite.png"))
SOURCE = "kal mujhe college jana hai!"
REQUIRED = ("कल", "मुझे", "जाना")


def check() -> None:
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        page = browser.new_page(viewport={"width": 1280, "height": 900}, locale="en-IN")
        try:
            for attempt in range(1, 7):
                print(f"PUBLIC_APP_ATTEMPT {attempt}/6", flush=True)
                try:
                    page.goto(URL, wait_until="domcontentloaded", timeout=90000)
                    page.get_by_role("button", name=re.compile(r"Convert to Hindi")).wait_for(timeout=90000)
                    break
                except PlaywrightTimeout:
                    if attempt == 6:
                        raise RuntimeError("Public Streamlit UI did not become available; model was not verified")
                    time.sleep(75)

            page.locator("textarea").first.fill(SOURCE)
            page.get_by_role("button", name=re.compile(r"Convert to Hindi")).click()
            page.get_by_text("Generated by IndicXlit", exact=True).wait_for(timeout=300000)
            result_el = page.locator('[data-testid="stCode"]').first
            result_el.wait_for(timeout=15000)
            result = result_el.inner_text().strip()
            if any(part not in result for part in REQUIRED):
                raise AssertionError(f"Actual public IndicXlit result lacked expected Hindi tokens: {result!r}")
            if SOURCE == result or not re.search(r"[\u0900-\u097F]", result):
                raise AssertionError("Public output is not a real Devanagari conversion")
            print(f"PUBLIC_INDICXLIT_CONVERSION_PASS input={SOURCE!r} output={result!r}", flush=True)
            page.screenshot(path=str(SCREENSHOT), full_page=True)
        except Exception:
            page.screenshot(path=str(SCREENSHOT), full_page=True)
            raise
        finally:
            browser.close()


if __name__ == "__main__":
    check()
