#!/usr/bin/env python3
"""Independent IndicWrite release gates.

No model mocking, checkpoint substitution, deployment mutation or private
BharatGen access. Offline inventory and external Chromium results are separate.
Only external browser results may count towards a public inference smoke.
"""
from __future__ import annotations

