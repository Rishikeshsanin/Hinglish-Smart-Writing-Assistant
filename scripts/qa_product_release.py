import csv
import json
import os
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_URL = "https://hinglish-smart-writing-assistant-indicwrite-rishi.streamlit.app/"
TEN_ROMAN_CASES = (
    "kal mujhe college jana hai!",
    "aaj mausam bahut accha hai!",
    "namaste dosto, aap kaise ho?",
    "main ghar ja raha hoon.",
    "mujhe paani chahiye.",
    "muje tumse baat karni hai.",
    "mai theek hu.",
    "ap kahan ho?",
    "bahot accha laga.",
    "kripya jaldi aana.",
)
VIEWPORTS = (
    ("mobile-320", 320, 700),
    ("mobile-390", 390, 844),
    ("tablet-768", 768, 1024),
    ("desktop-1440", 1440, 900),
)


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def commit_id():
    if os.getenv("GITHUB_SHA"):
        return os.environ["GITHUB_SHA"]
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True,
            stderr=subprocess.DEVNULL, timeout=5,
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return "unavailable"


def write_json(path, evidence):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(evidence, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def inventory(output):
    """Repository facts, NOT execution of the real model or live website."""
    required = [
        "app.py", "cloud_app.py", "src/indicwrite/core.py",
        "src/indicwrite/engine.py", "evaluation/cases.csv",
        "evaluation/results/predictions.csv", "tests/test_product_acceptance.py",
    ]
    rows = []
    cases = ROOT / "evaluation/cases.csv"
    predictions = ROOT / "evaluation/results/predictions.csv"
    if cases.exists() and predictions.exists():
        with cases.open(encoding="utf-8-sig", newline="") as f:
            n_cases = len(list(csv.DictReader(f)))
        with predictions.open(encoding="utf-8-sig", newline="") as f:
            n_predictions = len(list(csv.DictReader(f)))
    else:
        n_cases = n_predictions = 0
    evidence = {
        "generated_utc": utc_now(), "commit": commit_id(),
        "mode": "offline-inventory", "real_model_executed": False,
        "external_public_browser_executed": False,
        "required_files": {item: (ROOT / item).is_file() for item in required},
        "frozen_case_count": n_cases, "recorded_prediction_count": n_predictions,
        "existing_real_model_evidence": "https://github.com/Rishikeshsanin/Hinglish-Smart-Writing-Assistant/actions/runs/40870311669",
        "public_release_verdict": "BLOCKED: offline inventory cannot certify production",
    }
    write_json(output, evidence)
    print(json.dumps(evidence, ensure_ascii=False, indent=2))
    if not all(evidence["required_files"].values()) or (n_cases, n_predictions) != (40, 40):
        return 1
    return 0


def _record_page_errors(page, errors):
    page.on("pageerror", lambda exc: errors.append(str(exc)))


def _convert(page, source, preserve="", timeout_ms=300000):
    """Perform a real frontend click. No fake API routes or mock results."""
    from playwright.sync_api import expect

    preserve_box = page.get_by_role(
        "textbox", name=re.compile("Keep English words unchanged", re.I)
    )
    preserve_box.fill(preserve)
    preserve_box.press("Tab")  # commit Streamlit on_change
    text_box = page.locator("textarea").first
    text_box.fill(source)
    text_box.press("Tab")
    page.get_by_role("button", name=re.compile("Convert to Hindi", re.I)).click()
    expect(page.get_by_text("Generated by IndicXlit", exact=True)).to_be_visible(
        timeout=timeout_ms
    )
    code = page.locator('[data-testid="stCode"]').first
    expect(code).to_be_visible(timeout=15000)
    result = code.inner_text().strip()
    assert result != source, "No actual conversion occurred"
    assert re.search("[\u0900-\u097f]", result), "No Devanagari in real UI output"
    return result


def browser_smoke(url, target, output_dir, ten_cases=False):
    """Browser acceptance against a real Streamlit server, public or local."""
    try:
        from playwright.sync_api import sync_playwright, expect
    except ImportError as exc:
        raise RuntimeError("Install playwright==1.56.0 and Chromium first") from exc

    if target == "public" and url.rstrip("/") != PUBLIC_URL.rstrip("/"):
        raise ValueError("Public verification must use the established canonical Streamlit URL")
    if target == "local" and urlparse(url).hostname not in ("localhost", "127.0.0.1"):
        raise ValueError("Local QA must use loopback; never mislabel a remote URL as local")

    output_dir.mkdir(parents=True, exist_ok=True)
    evidence = {
        "generated_utc": utc_now(), "commit": commit_id(),
        "workflow_url": ("https://github.com/Rishikeshsanin/Hinglish-Smart-Writing-Assistant/actions/runs/" + os.environ["GITHUB_RUN_ID"]) if os.getenv("GITHUB_RUN_ID") else None,
        "target": target, "url": url, "mode": "real-browser",
        "mocked_model": False, "real_model_provenance": "backend must be independently audited",
        "viewport_results": [], "conversions": [],
        "checks": {}, "page_errors": [], "cold_page_seconds": None,
        "warm_convert_seconds": None,
        "cold_model_load_seconds": None,
        "memory_peak_mib": None, "resource_health": "not measured externally",
        "public_release_verdict": "BLOCKED: A/B/C integration and external release gates not yet certified",
    }
    artifact_path = output_dir / "browser-evidence.json"
    start = time.monotonic()
    try:
        with sync_playwright() as p:
            browser = p.chromium.launch(headless=True, args=["--no-sandbox"])
            try:
                context = browser.new_context(
                    viewport={"width": 1440, "height": 900}, locale="en-IN",
                    accept_downloads=True, permissions=["clipboard-read", "clipboard-write"],
                )
                page = context.new_page()
                _record_page_errors(page, evidence["page_errors"])
                last_error = None
                for attempt in range(1, 7):
                    try:
                        page.goto(url, wait_until="domcontentloaded", timeout=90000)
                        expect(page.get_by_role(
                            "button", name=re.compile("Convert to Hindi", re.I)
                        )).to_be_visible(timeout=90000)
                        evidence["checks"]["page_loaded"] = True
                        evidence["cold_page_seconds"] = round(time.monotonic() - start, 2)
                        evidence["load_attempts"] = attempt
                        break
                    except Exception as exc:
                        last_error = repr(exc)
                        page.screenshot(path=str(output_dir / f"load-attempt-{attempt}.png"))
                        if attempt == 6:
                            raise RuntimeError(
                                "Public UI never exposed Convert control; NO inference verified: "
                                + str(last_error)
                            ) from exc
                        time.sleep(20)

                source = page.locator("textarea").first
                expect(source).to_be_visible(timeout=15000)
                assert source.get_attribute("aria-label") or page.get_by_text(
                    "Roman Hindi", exact=True
                ).count(), "Roman Hindi input missing accessible label"
                source.click()
                page.keyboard.press("Tab")
                focused = page.evaluate("document.activeElement?.tagName?.toLowerCase()")
                assert focused in ("input", "button", "textarea"), f"Keyboard tab order broken: {focused}"
                evidence["checks"]["keyboard_focus"] = True

                # Blank input must fail before any expensive neural bootstrap.
                source.fill("  ")
                source.press("Tab")
                page.get_by_role("button", name=re.compile("Convert to Hindi", re.I)).click()
                expect(page.get_by_text(re.compile("Enter a Roman-Hindi sentence", re.I))).to_be_visible(timeout=20000)
                assert page.get_by_text("Generated by IndicXlit", exact=True).count() == 0
                evidence["checks"]["blank_rejected"] = True

                # Invalid preserve input must fail BEFORE attempting model load.
                source.fill("kal")
                source.press("Tab")
                protected = page.get_by_role(
                    "textbox", name=re.compile("Keep English words unchanged", re.I)
                )
                protected.fill("C++")
                protected.press("Tab")
                page.get_by_role("button", name=re.compile("Convert to Hindi", re.I)).click()
                expect(page.get_by_text(
                    re.compile("unsupported", re.I)
                )).to_be_visible(timeout=20000)
                assert page.get_by_text("Generated by IndicXlit", exact=True).count() == 0
                evidence["checks"]["invalid_preserve_rejected"] = True

                started = time.monotonic()
                expected = "कल मुझे कॉलेज जाना है!"
                output = _convert(page, TEN_ROMAN_CASES[0])
                assert output == expected, f"Real official-model canonical sentence changed: {output!r}"
                evidence["conversions"].append({"input": TEN_ROMAN_CASES[0], "output": output})
                evidence["checks"]["real_hindi_conversion"] = True
                evidence["cold_model_load_seconds"] = round(time.monotonic() - started, 2)

                # Real Unicode TXT download, NOT merely a visible download button.
                with page.expect_download(timeout=30000) as transfer:
                    page.get_by_role("button", name="Download result (.txt)").click()
                saved = transfer.value.path().read_bytes().decode("utf-8-sig")
                assert saved == output, f"UTF-8 download differs from visible Hindi: {saved!r}"
                evidence["checks"]["unicode_download"] = True

                # Manual review is explicitly NOT an AI rewrite.
                review = page.get_by_text("Review and refine Hindi manually", exact=True)
                expect(review).to_be_visible(timeout=15000)
                review.click()
                edited = page.get_by_role("textbox", name="Editable Hindi")
                expect(edited).to_be_visible(timeout=10000)
                edited.fill("नमस्ते 🚀 हिंदी")
                edited.press("Tab")
                with page.expect_download(timeout=30000) as transfer:
                    page.get_by_role("button", name="Download reviewed Hindi (.txt)").click()
                assert transfer.value.path().read_bytes().decode("utf-8-sig") == "नमस्ते 🚀 हिंदी"
                evidence["checks"]["manual_edit_download"] = True

                # The native Streamlit code component provides a copy action.
                copy_button = page.locator('[data-testid="stCode"]').first.locator("button").first
                if copy_button.count():
                    copy_button.click()
                    try:
                        copied = page.evaluate("navigator.clipboard.readText()")
                        assert copied == output, f"Clipboard mismatch: {copied!r}"
                        evidence["checks"]["clipboard_copy"] = True
                    except Exception as exc:
                        evidence["checks"]["clipboard_copy"] = False
                        evidence["clipboard_error"] = repr(exc)
                else:
                    evidence["checks"]["clipboard_copy"] = False

                started = time.monotonic()
                preserved = _convert(
                    page, "kal Python AI 42 https://example.org/a?q=1 हिंदी 🚀",
                    preserve="Python",
                )
                assert "कल" in preserved
                assert "Python AI 42 https://example.org/a?q=1 हिंदी 🚀" in preserved
                evidence["conversions"].append({
                    "input": "kal Python AI 42 https://example.org/a?q=1 हिंदी 🚀",
                    "preserve": "Python", "output": preserved,
                })
                evidence["checks"]["english_urls_numbers_unicode_preserved"] = True
                evidence["warm_convert_seconds"] = round(time.monotonic() - started, 2)

                if ten_cases:
                    for sentence in TEN_ROMAN_CASES[1:]:
                        result = _convert(page, sentence)
                        evidence["conversions"].append({"input": sentence, "output": result})
                    evidence["checks"]["ten_real_cases_ran"] = len(evidence["conversions"]) >= 10
                else:
                    evidence["checks"]["ten_real_cases_ran"] = False
                    evidence["ten_case_status"] = "opt-in extended QA not executed"

                # Public research paths must be off; fail on unexpected exposure.
                assert page.get_by_text("Private BharatGen research", exact=False).count() == 0, (
                    "Private BharatGen interface exposed in a publicly reachable app"
                )
                evidence["checks"]["private_bharatgen_not_public"] = True
                grammar = page.get_by_role("button", name="Improve Hindi grammar (research)")
                if grammar.count():
                    assert not grammar.is_enabled(), "Unvalidated grammar correction enabled"
                evidence["checks"]["unvalidated_grammar_disabled"] = True
                translation = page.get_by_role("button", name="Translate to English")
                if translation.count() and translation.is_enabled():
                    translation.click()
                    expect(page.get_by_text(
                        re.compile("English output.*Helsinki-NLP OPUS-MT", re.I)
                    )).to_be_visible(timeout=300000)
                    english_codes = page.locator('[data-testid="stCode"]')
                    english_output = english_codes.last.inner_text().strip()
                    assert re.search("[A-Za-z]", english_output) and english_output != preserved
                    evidence["checks"]["enabled_translation_real"] = True
                    evidence["enabled_translation_output"] = english_output
                else:
                    evidence["checks"]["enabled_translation_real"] = "not enabled"

                for label, width, height in VIEWPORTS:
                    if label == "desktop-1440":
                        screen = page
                        page.screenshot(path=str(output_dir / f"{label}.png"), full_page=True)
                    else:
                        viewport_context = browser.new_context(
                            viewport={"width": width, "height": height}, locale="en-IN"
                        )
                        screen = viewport_context.new_page()
                        _record_page_errors(screen, evidence["page_errors"])
                        screen.goto(url, wait_until="domcontentloaded", timeout=90000)
                        expect(screen.get_by_role(
                            "button", name=re.compile("Convert to Hindi", re.I)
                        )).to_be_visible(timeout=90000)
                        screen.screenshot(path=str(output_dir / f"{label}.png"), full_page=True)
                    overflow = screen.evaluate(
                        "document.documentElement.scrollWidth > window.innerWidth + 4"
                    )
                    result = {"viewport": label, "width": width, "overflow": bool(overflow)}
                    evidence["viewport_results"].append(result)
                    assert not overflow, f"Horizontal document overflow at {width}px"
                    if label != "desktop-1440":
                        viewport_context.close()
                evidence["checks"]["responsive_320_390_768_1440"] = True

                page.get_by_role("button", name="Clear", exact=True).click()
                expect(source).to_have_value("", timeout=20000)
                assert page.get_by_text("Generated by IndicXlit", exact=True).count() == 0
                evidence["checks"]["clear_invalidates_output"] = True
                assert not evidence["page_errors"], f"Browser JS exceptions: {evidence['page_errors']}"
                evidence["checks"]["no_browser_js_exceptions"] = True
                evidence["browser_smoke"] = "PASS"
                # Browser smoke PASS is deliberately not synonymous with release LIVE.
                print("REAL_BROWSER_SMOKE_PASS", target, url, flush=True)
                context.close()
            finally:
                browser.close()
        return 0
    except Exception as exc:
        evidence["browser_smoke"] = "FAIL"
        evidence["failure"] = repr(exc)
        print(f"REAL_BROWSER_SMOKE_FAIL: {exc!r}", file=sys.stderr, flush=True)
        return 1
    finally:
        evidence["completed_utc"] = utc_now()
        evidence["elapsed_seconds"] = round(time.monotonic() - start, 2)
        write_json(artifact_path, evidence)
        print("Evidence:", artifact_path, flush=True)


def release_gate(evidence, integrations=None):
    """Conservative coordinator handoff; no automatic release from a UI screenshot."""
    integrations = integrations or {}
    reasons = []
    if evidence.get("target") != "public" or evidence.get("browser_smoke") != "PASS":
        reasons.append("no passing real external canonical Streamlit browser conversion")
    for key in (
        "real_hindi_conversion", "english_urls_numbers_unicode_preserved",
        "ten_real_cases_ran", "unicode_download", "manual_edit_download",
        "clipboard_copy", "blank_rejected",
        "responsive_320_390_768_1440", "keyboard_focus", "invalid_preserve_rejected",
        "private_bharatgen_not_public", "unvalidated_grammar_disabled",
        "clear_invalidates_output", "no_browser_js_exceptions",
    ):
        if evidence.get("checks", {}).get(key) is not True:
            reasons.append("missing browser acceptance: " + key)
    if not integrations.get("agents_a_b_c_merged_into_main"):
        reasons.append("Agents A/B/C not independently verified merged")
    if not re.fullmatch(r"[0-9a-f]{40}", str(evidence.get("commit", ""))) or evidence.get("commit") != integrations.get("integrated_main_sha"):
        reasons.append("external browser run SHA does not match documented integrated main")
    if not str(evidence.get("workflow_url") or "").startswith("https://github.com/Rishikeshsanin/Hinglish-Smart-Writing-Assistant/actions/runs/"):
        reasons.append("missing verifiable GitHub Actions public-browser evidence URL")
    if not integrations.get("all_required_ci_green") or not integrations.get("official_model_parity_green"):
        reasons.append("required CI and official checkpoint parity not evidenced")
    if not integrations.get("no_unresolved_p0_p1"):
        reasons.append("unresolved critical/high severity regressions not cleared")
    if evidence.get("checks", {}).get("enabled_translation_real") not in (True, "not enabled"):
        reasons.append("enabled translation not demonstrated with actual model output")
    if not integrations.get("enabled_model_quality_and_license_review"):
        reasons.append("enabled AI model quality/licensing not approved")
    if not integrations.get("production_stability_review"):
        reasons.append("cold/warm uptime, failures, throughput and resource review pending")
    return {"decision": "BLOCKED" if reasons else "READY_FOR_COORDINATOR_REVIEW",
            "reasons": reasons, "reviewed_utc": utc_now()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mode", choices=("inventory", "browser", "gate"), default="inventory")
    parser.add_argument("--target", choices=("public", "local"), default="public")
    parser.add_argument("--url", default=PUBLIC_URL)
    parser.add_argument("--ten-cases", action="store_true")
    parser.add_argument("--artifacts", type=Path, default=Path("qa-artifacts"))
    parser.add_argument("--evidence", type=Path)
    parser.add_argument("--integration", type=Path,
                        help="Coordinator-reviewed JSON gate evidence; never inferred from screenshots")
    args = parser.parse_args()

    if args.mode == "inventory":
        return inventory(args.artifacts / "offline-inventory.json")
    if args.mode == "browser":
        return browser_smoke(args.url, args.target, args.artifacts, args.ten_cases)
    if args.evidence is None:
        parser.error("--mode gate requires --evidence")
    evidence = json.loads(args.evidence.read_text(encoding="utf-8"))
    integrations = json.loads(args.integration.read_text(encoding="utf-8")) if args.integration else {}
    result = release_gate(evidence, integrations)
    write_json(args.artifacts / "release-decision.json", result)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 0 if result["decision"] == "READY_FOR_COORDINATOR_REVIEW" else 2


if __name__ == "__main__":
    raise SystemExit(main())
