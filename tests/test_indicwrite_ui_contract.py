"""Source-level UI contract checks: no checkpoint or browser inference is claimed.

These checks run without Streamlit/model weights in lightweight CI.
The existing scripts/browser_smoke.py verifies genuine real-model browser output separately.
"""
import ast
from pathlib import Path

APP = Path(__file__).resolve().parents[1] / "app.py"


def source():
    return APP.read_text(encoding="utf-8")


def test_native_ui_remains_valid_python():
    ast.parse(source())


def test_native_convert_button_and_real_engine_contract():
    code = source()
    assert 'st.button("Convert to Hindi", type="primary"' in code
    assert "from indicwrite.engine import load_indicxlit" in code
    assert "model = load_indicxlit()" in code
    assert "result = transliterate_text(text, model, preserve_terms=preserve_terms)" in code
    assert "Generated by IndicXlit" in code
    assert "No substitute output was generated." in code
    assert "parse_preserve_terms(protected)" in code


def test_human_editor_copy_download_and_clear_preserved():
    code = source()
    assert 'st.text_area("Editable Hindi", key="human_edit"' in code
    assert "Human-edited draft: this is NOT an AI grammar correction." in code
    assert "st.code(st.session_state[\"converted_text\"]" in code
    assert 'file_name="indicwrite-reviewed-hindi.txt"' in code
    assert 'file_name="indicwrite-hindi.txt"' in code
    assert 'st.button("Clear", use_container_width=True, on_click=reset)' in code
    assert "on_change=clear_result" in code
    assert "max_chars=500" in code


def test_responsive_and_accessibility_style_intent():
    code = source()
    assert "label_visibility=\"visible\"" in code
    assert "@media (max-width: 800px)" in code
    assert "@media (max-width: 390px)" in code
    assert "prefers-reduced-motion: reduce" in code
    assert ":focus-visible" in code
